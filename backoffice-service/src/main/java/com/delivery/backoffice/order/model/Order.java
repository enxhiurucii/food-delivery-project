package com.delivery.backoffice.order.model;

import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.Objects;

import com.delivery.backoffice.order.enums.FulfillmentType;
import com.delivery.backoffice.order.enums.OrderStatus;
import com.delivery.backoffice.order.exception.InvalidStatusTransitionException;
import lombok.Getter;
import org.springframework.data.annotation.Id;
import org.springframework.data.annotation.Version;
import org.springframework.data.mongodb.core.index.CompoundIndex;
import org.springframework.data.mongodb.core.index.CompoundIndexes;
import org.springframework.data.mongodb.core.mapping.Document;

/**
 * The restaurant's view of an order and the AUTHORITATIVE owner of its lifecycle. The id is the order id
 * generated by the webshop, which makes consuming "order.placed" idempotent (same id = same order).
 *
 * <p>All business rules live here (not in services/controllers): allowed transitions, timeline,
 * closing time, settling deferred payments.
 */
@Getter
@Document("orders")
@CompoundIndexes({
        @CompoundIndex(name = "restaurant_status_placed", def = "{'restaurantId': 1, 'status': 1, 'placedAt': -1}"),
        @CompoundIndex(name = "restaurant_closed", def = "{'restaurantId': 1, 'closedAt': 1}"),
        // driver available-deliveries: fulfillmentType + status + driverId (null = unclaimed)
        @CompoundIndex(name = "driver_available", def = "{'fulfillmentType': 1, 'status': 1, 'driverId': 1}"),
        // driver active-delivery: look up by assigned driver id
        @CompoundIndex(name = "driver_active", def = "{'driverId': 1, 'status': 1}")
})
public class Order {

    @Id
    private String id;
    private String restaurantId;
    private String customerId;
    private String customerName;
    private List<OrderLine> lines = new ArrayList<>();
    private long subtotalCents;
    private long deliveryFeeCents;
    private long totalCents;
    private FulfillmentType fulfillmentType;
    private DeliveryAddress deliveryAddress;
    private String notes;
    private Payment payment;
    private OrderStatus status;
    private List<StatusChange> statusHistory = new ArrayList<>();
    private Instant placedAt;
    private Instant closedAt;
    private String driverId;
    private String driverName;
    @Version
    private Long version;

    protected Order() {
    }

    public static Order place(String id, String restaurantId, String customerId, String customerName,
                              List<OrderLine> lines, long deliveryFeeCents, FulfillmentType fulfillmentType,
                              DeliveryAddress deliveryAddress, String notes, Payment payment, Instant placedAt) {
        Objects.requireNonNull(id, "id");
        if (lines == null || lines.isEmpty()) {
            throw new IllegalArgumentException("An order needs at least one line");
        }
        if (fulfillmentType == FulfillmentType.DELIVERY && deliveryAddress == null) {
            throw new IllegalArgumentException("A delivery order needs an address");
        }
        Order order = new Order();
        order.id = id;
        order.restaurantId = restaurantId;
        order.customerId = customerId;
        order.customerName = customerName;
        order.lines = new ArrayList<>(lines);
        order.subtotalCents = lines.stream().mapToLong(OrderLine::totalCents).sum();
        order.deliveryFeeCents = fulfillmentType == FulfillmentType.DELIVERY ? deliveryFeeCents : 0;
        order.totalCents = order.subtotalCents + order.deliveryFeeCents;
        order.fulfillmentType = fulfillmentType;
        order.deliveryAddress = fulfillmentType == FulfillmentType.DELIVERY ? deliveryAddress : null;
        order.notes = notes;
        order.payment = payment;
        order.status = OrderStatus.PLACED;
        order.placedAt = placedAt;
        order.statusHistory.add(new StatusChange(OrderStatus.PLACED, placedAt));
        return order;
    }

    public StatusChange changeStatus(OrderStatus next, Instant at) {
        if (!status.canTransitionTo(next, fulfillmentType)) {
            throw new InvalidStatusTransitionException(id, status, next, fulfillmentType);
        }
        StatusChange change = new StatusChange(next, at);
        status = next;
        statusHistory.add(change);
        if (next.isTerminal()) {
            closedAt = at;
        }
        if (next.isCompleted() && payment.status() == Payment.Status.PENDING) {
            payment = payment.markPaid(); // cash/card collected at the counter or by the courier
        }
        return change;
    }

    public void assignDriver(String driverId, String driverName) {
        if (this.driverId != null) {
            throw new IllegalStateException("Order " + id + " already has a driver assigned");
        }
        this.driverId = driverId;
        this.driverName = driverName;
    }

    public boolean hasDriver() {
        return driverId != null;
    }

    /** Monotonic per-order sequence number shared with consumers for idempotency/ordering. */
    public int statusSequence() {
        return statusHistory.size();
    }
}
